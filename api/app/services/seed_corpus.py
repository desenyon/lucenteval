def seed_corpus(db: Session, version: str = CORPUS_VERSION, skip_existing: bool = True) -> int:
    """Insert all prompts into the database. Returns count of inserted rows."""
    if skip_existing:
        existing = db.query(Prompt).filter(Prompt.corpus_version == version).count()
        if existing > 0:
            return 0

    inserted = 0
    for raw in ALL_PROMPTS:
        p = Prompt(
            id=uuid.uuid4(),
            text=raw["text"],
            category=raw["category"],
            subcategory=raw.get("subcategory"),
            severity=raw["severity"],
            expected_behavior=raw["expected_behavior"],
            corpus_version=version,
            is_active=True,
            in_quarantine=False,
        )
        db.add(p)
        inserted += 1

    db.commit()
    return inserted
